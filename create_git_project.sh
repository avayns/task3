#!/bin/bash
#Проверяем, передано ли название проекта
if [ -z "$1" ]; then 
echo "Ошибка: Укажите название проекта!" 
echo "Пример: ./create_git_project.sh my_super_project" 
exit 1 
fi

#Сохраняем входные параметры
PROJECT_NAME=$1 
CUSTOM_TEXT=$2

#Задаем абсолютный путь к папке projects, чтобы скрипт работал из любой директории
PROJECTS_DIR="$HOME/projects" 
TARGET_DIR="$PROJECTS_DIR/$PROJECT_NAME"

#1. Создаем папку ~/projects, если её еще нет
mkdir -p "$PROJECTS_DIR"

#2. Создаем папку с названием проекта
mkdir -p "$TARGET_DIR" 
echo "Папка '$PROJECT_NAME' успешно создана в $PROJECTS_DIR"

#3. Переходим в папку проекта для инициализации Git
cd "$TARGET_DIR" || exit

#4. Инициализируем Git (скрываем лишний вывод)
git init > /dev/null 2>&1

#5. Формируем текст для README.md
#Используем \n для переносов строк (как в методичке) и флаг -e при записи
echo "# $PROJECT_NAME" > README.md
echo "" >> README.md

cat << 'EOF' >> README.md
# Мем про кота-программиста
## Ситуация:

Однажды, жил был кот, который любил поспать на клавиатуре.

И вот код, который он случайно вывел, oпять уснув на клаве:

```python
print("Мурр, мяу, мяу, мяуу!!!")
while True: 
    print("Я хочу спать")
```

__Вывод:__ Кот - лучший Python разработчик :D

Вот такая вот забавная история!) 

_мяу_

##ASCII-графика
                     (`.-';)
                   .-'     ;
               _.-'   , `,-
         _ _.-'     .'  /._
       .' `  _.-.  /  ,'._;)
      (       .  )-| (
       )`,_ ,'_,'  \_;)
('_  _,'.' (___,))
 `-:;.-'
EOF

#6. Делаем первый коммит
git add README.md 
git commit -m "первый коммит" > /dev/null 2>&1

#7. Возвращаемся обратно в папку, откуда запускали скрипт (чтобы не путать пользователя)
cd - > /dev/null
echo "Файл README.md заполнен для проекта '$PROJECT_NAME'."
